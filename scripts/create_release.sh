#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
VERSION="${VERSION:-1.3.2}"
SDKROOT_PATH="${SDKROOT:-$(xcrun --show-sdk-path 2>/dev/null || echo /Library/Developer/CommandLineTools/SDKs/MacOSX.sdk)}"
CODESIGN_IDENTITY="${CODESIGN_IDENTITY:--}"

cd "$ROOT_DIR"

if [[ ! -d "$SDKROOT_PATH" ]]; then
  echo "SDK not found at: $SDKROOT_PATH" >&2
  exit 1
fi

echo "Building release binary..."
SDKROOT="$SDKROOT_PATH" swift build -c release

BIN_DIR="$ROOT_DIR/.build/release"
PRODUCT_BIN="$BIN_DIR/MetalDuck"
BUNDLE_DIR="$BIN_DIR/MetalDuck_MetalDuck.bundle"
ICON_FILE="$ROOT_DIR/Sources/MetalDuck/Assets/AppIcon.icns"

if [[ ! -f "$PRODUCT_BIN" ]]; then
  echo "Release binary not found: $PRODUCT_BIN" >&2
  exit 1
fi

APP_NAME="MetalDuck"
APP_BUNDLE_NAME="${APP_NAME}.app"
STAGE_DIR="$ROOT_DIR/dist/MetalDuck-macos-arm64"
DMG_STAGE_DIR="$ROOT_DIR/dist/MetalDuck-dmg-root"
APP_DIR="$STAGE_DIR/$APP_BUNDLE_NAME"
CONTENTS_DIR="$APP_DIR/Contents"
MACOS_DIR="$CONTENTS_DIR/MacOS"
RESOURCES_DIR="$CONTENTS_DIR/Resources"
DMG_PATH="$ROOT_DIR/dist/MetalDuck-$VERSION.dmg"

rm -rf "$ROOT_DIR/dist/"*
rm -rf "$STAGE_DIR" "$DMG_STAGE_DIR"
mkdir -p "$MACOS_DIR" "$RESOURCES_DIR" "$DMG_STAGE_DIR"

cp "$PRODUCT_BIN" "$MACOS_DIR/$APP_NAME"
chmod +x "$MACOS_DIR/$APP_NAME"
if [[ -d "$BUNDLE_DIR" ]]; then
  cp -R "$BUNDLE_DIR" "$RESOURCES_DIR/"
fi
if [[ -f "$ICON_FILE" ]]; then
  echo "Found icon at $ICON_FILE, copying to $RESOURCES_DIR/AppIcon.icns"
  cp "$ICON_FILE" "$RESOURCES_DIR/AppIcon.icns"
else
  echo "ICON NOT FOUND AT $ICON_FILE" >&2
fi

cat > "$CONTENTS_DIR/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>
  <string>MetalDuck</string>
  <key>CFBundleDisplayName</key>
  <string>MetalDuck</string>
  <key>CFBundleIdentifier</key>
  <string>com.nycolazs.metaldduck</string>
  <key>CFBundleVersion</key>
  <string>$VERSION</string>
  <key>CFBundleShortVersionString</key>
  <string>$VERSION</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleExecutable</key>
  <string>MetalDuck</string>
  <key>CFBundleIconFile</key>
  <string>AppIcon.icns</string>
  <key>LSMinimumSystemVersion</key>
  <string>15.0</string>
  <key>NSPrincipalClass</key>
  <string>NSApplication</string>
</dict>
</plist>
PLIST

touch "$CONTENTS_DIR/PkgInfo"
echo "APPL????" > "$CONTENTS_DIR/PkgInfo"

# Re-sign the full app bundle after assembling it, so Gatekeeper sees a valid signature.
codesign --force --deep --sign "$CODESIGN_IDENTITY" "$APP_DIR"
codesign --verify --deep --strict --verbose=2 "$APP_DIR"

# Assemble the DMG stage directory
cp -R "$APP_DIR" "$DMG_STAGE_DIR/"
ln -s /Applications "$DMG_STAGE_DIR/Applications"

# DMG background (generated by scripts/generate_brand_assets.swift). One TIFF holds
# the 1x and 2x images so Finder picks the sharp one on Retina displays.
# DMG_THEME=light bash scripts/create_release.sh uses the light window instead.
DMG_THEME="${DMG_THEME:-dark}"
DMG_BG_DIR="$ROOT_DIR/Designs/DMG/$DMG_THEME"
if [[ ! -f "$DMG_BG_DIR/background.png" ]]; then
  echo "No DMG background for theme '$DMG_THEME' in $DMG_BG_DIR" >&2
  exit 1
fi
mkdir -p "$DMG_STAGE_DIR/.background"
tiffutil -cathidpicheck "$DMG_BG_DIR/background.png" "$DMG_BG_DIR/background@2x.png" \
  -out "$DMG_STAGE_DIR/.background/background.tiff"

# Volume icon shown on the desktop and in the Finder sidebar while mounted.
cp "$ICON_FILE" "$DMG_STAGE_DIR/.VolumeIcon.icns"

# Create a temporary empty DMG to configure layout
TEMP_DMG="${DMG_PATH}.temp.dmg"
MOUNT_DIR=$(mktemp -d /tmp/metaldduck_mount.XXXXXX)

# Robust cleanup on exit
cleanup() {
  echo "Cleaning up..."
  hdiutil detach "$MOUNT_DIR" 2>/dev/null || true
  rm -f "$TEMP_DMG"
  rmdir "$MOUNT_DIR" 2>/dev/null || true
}
trap cleanup EXIT

rm -f "$TEMP_DMG" "$DMG_PATH"

echo "Creating temporary DMG..."
hdiutil create -srcfolder "$DMG_STAGE_DIR" -volname "MetalDuck" -fs HFS+ -format UDRW -ov "$TEMP_DMG"

echo "Mounting temporary DMG..."
hdiutil attach "$TEMP_DMG" -mountpoint "$MOUNT_DIR" -noautoopen

# Mark the volume as having a custom icon, if the developer tools provide SetFile.
if SETFILE="$(xcrun -f SetFile 2>/dev/null)"; then
  "$SETFILE" -a C "$MOUNT_DIR"
else
  echo "SetFile not found; the mounted volume will use the generic disk icon." >&2
fi

echo "Configuring DMG layout..."
# Window content is 660 x 400 pt, matching Designs/DMG/background.png. Icon
# positions match the platforms drawn in scripts/generate_brand_assets.swift.
osascript <<APPLESCRIPT
tell application "Finder"
    set theWindow to make new Finder window to (POSIX file "$MOUNT_DIR") as alias
    tell theWindow
        open
        set current view to icon view
        set toolbar visible to false
        set statusbar visible to false
        set sidebar width to 0
        set the bounds to {300, 120, 960, 548} -- 400 pt content + 28 pt title bar
    end tell

    set viewOptions to the icon view options of theWindow
    tell viewOptions
        set icon size to 128
        set text size to 13
        set label position to bottom
        set shows item info to false
        set shows icon preview to false
        set arrangement to not arranged
        set background picture to (POSIX file "$MOUNT_DIR/.background/background.tiff") as alias
    end tell

    set position of item "MetalDuck.app" of theWindow to {170, 190}
    set position of item "Applications" of theWindow to {490, 190}

    update every item of theWindow
    delay 2
    close theWindow
end tell
APPLESCRIPT

# Make sure Finder's layout file is on disk before the image is sealed.
sync
sleep 1

echo "Detaching DMG..."
hdiutil detach "$MOUNT_DIR"

echo "Converting to final DMG..."
hdiutil convert "$TEMP_DMG" -format UDZO -imagekey zlib-level=9 -o "$DMG_PATH"

echo "Finalizing output..."
rm -rf "$STAGE_DIR" "$DMG_STAGE_DIR"

echo "Release package created: $DMG_PATH"
